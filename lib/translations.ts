const escapePattern = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
function matchTemplate(template: string, value: string): Record<string, string> | null {
  const ids: string[] = [];
  const pattern = template.split(/(\{\d+\})/g).map(part => {
    const id = part.match(/^\{(\d+)\}$/)?.[1];
    if (id !== undefined) { ids.push(id); return "([\\s\\S]*?)"; }
    return escapePattern(part);
  }).join("");
  if (!ids.length) return null;
  const match = value.match(new RegExp(`^${pattern}$`));
  return match ? Object.fromEntries(ids.map((id, index) => [id, match[index + 1]])) : null;
}

export function translate(language: Language, message: string, values: Record<string, string | number> = {}): string {
  if (!message.trim()) return message;
  const key = message.trim();
  let source = key;
  let args = values;
  if (!Object.hasOwn(english, source)) {
    for (const [zh, en] of Object.entries(english)) {
      if (en === key) { source = zh; break; }
      const captures = matchTemplate(zh, key) ?? matchTemplate(en, key);
      if (captures) { source = zh; args = captures; break; }
    }
  }
  const template = language === "en" ? english[source] ?? source : source;
  const result = template.replace(/\{(\d+)\}/g, (token, id) => String(args[id] ?? token));
  return (message.match(/^\s*/)?.[0] ?? "") + result + (message.match(/\s*$/)?.[0] ?? "");
}
