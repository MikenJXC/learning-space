import assert from 'node:assert/strict';
import { courseProgress, readingPercent } from '../lib/course-progress.ts';
import { docxReadingPosition, docxRestoreFraction, DOCX_READING_UNITS } from '../lib/docx-reading.ts';
const slide={id:'s',kind:'slides',fileName:'slides.pptx',progress:{page:3,totalPages:10,updatedAt:1}};
const study={id:'d',kind:'study',fileName:'notes.docx',progress:{page:5001,totalPages:10000,updatedAt:2}};
const chapter={id:'c',chapterNumber:1,assets:[slide,study]};
assert.equal(courseProgress({},chapter).lastRead.id,'s');
assert.equal(courseProgress({progressBasis:'study'},chapter).lastRead.id,'d');
assert.equal(courseProgress({progressBasis:'study'},{...chapter,assets:[slide]}).progress,null);
assert.equal(courseProgress({},undefined).progress,null);
assert.equal(readingPercent(3,10,'slides.pptx'),30);
assert.equal(readingPercent(1,10000,'notes.docx'),0);
assert.equal(readingPercent(10000,10000,'notes.docx'),100);
assert.equal(docxReadingPosition(0,2000,1000),1);
assert.equal(docxReadingPosition(1000,2000,1000),DOCX_READING_UNITS);
assert.equal(docxReadingPosition(0,1000,1000),DOCX_READING_UNITS);
assert.equal(docxRestoreFraction(null),0);
assert.equal(docxRestoreFraction({page:10000,totalPages:10000,updatedAt:1}),1);
assert.equal(docxRestoreFraction({page:1,totalPages:10000,updatedAt:1}),0);
const secondStudy={...study,id:'d2',progress:{...study.progress,updatedAt:3}};
assert.equal(courseProgress({progressBasis:'study'},{...chapter,assets:[slide,study,secondStudy]}).lastRead.id,'d2');
console.log('Per-course source isolation, no fallback, latest matching file, DOCX scroll/restore and percentage tests passed.');
