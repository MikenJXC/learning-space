import assert from 'node:assert/strict';
import { mergeUploadFiles, selectReadingAsset } from '../lib/study-files.ts';
const first = {name:'学习文档.docx',size:12,lastModified:1};
const second = {name:'补充材料.pdf',size:14,lastModified:2};
const renamedVersion = {name:'学习文档.docx',size:18,lastModified:3};
const initial = [first];
assert.deepEqual(mergeUploadFiles(initial,[second,first]),[first,second]);
assert.deepEqual(initial,[first]);
assert.deepEqual(mergeUploadFiles([first,second],[renamedVersion]),[first,second,renamedVersion]);
assert.deepEqual(mergeUploadFiles([],[first,first]),[first]);
assert.deepEqual(mergeUploadFiles([first],[]),[first]);
const asset = (id,time=0) => ({id,kind:'study',fileName:'same.docx',url:'/api/files/'+id,mimeType:'',size:0,progress:time?{page:3,totalPages:10,updatedAt:time}:null});
const a=asset('a',10), b=asset('b',20), c=asset('c');
const docs=[a,b,c];
assert.equal(selectReadingAsset(docs,'a'),a);
assert.equal(selectReadingAsset(docs,''),b);
assert.equal(selectReadingAsset(docs,'another-chapter-file'),b);
assert.equal(selectReadingAsset([],'a'),undefined);
assert.equal(selectReadingAsset([c,asset('d')],''),c);
assert.deepEqual(docs,[a,b,c]);
console.log('Study file queue accumulation/deduplication and independent reader selection passed.');
