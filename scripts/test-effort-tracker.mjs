import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
import * as effort from '../lib/study-effort.ts';

// Exercise the hook's clock and event logic without browser automation or a real account.
let now = Math.floor(Date.now() / 15000) * 15000, cleanup, currentStatus;
const document = new EventTarget(), window = new EventTarget(), timers = new Map(), requests = [];
document.visibilityState = 'visible'; document.hasFocus = () => true;
window.setInterval = (fn, ms) => { timers.set(ms, fn); return ms; };
const react = { useRef: current => ({ current }), useState: value => [value, next => { currentStatus = next; }], useEffect: fn => { cleanup = fn(); } };
const exports = {};
const context = vm.createContext({ exports, require: id => id === 'react' ? react : effort, document, window, Date: class extends Date { static now() { return now; } }, crypto: { randomUUID: () => '00000000-0000-4000-8000-000000000001' }, clearInterval: id => timers.delete(id), Element: class {}, fetch: async (_url, init) => { requests.push(JSON.parse(init.body)); return { ok: true }; } });
vm.runInContext(ts.transpileModule(fs.readFileSync('lib/use-study-effort.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, context);
const controls = exports.useStudyEffort('course', 1, ['slides', 'study']);
const tick = () => { now += 1000; timers.get(1000)(); };
const sync = async () => { await timers.get(15000)(); await Promise.resolve(); await Promise.resolve(); };
for (let i=0; i<5; i++) tick();
await sync(); assert.equal(requests.length, 0, 'No time before a document renders');
const rendered = new Event('learning-reading-ready'); rendered.detail = { assetId: 'slides' }; window.dispatchEvent(rendered);
for (let i=0; i<15; i++) tick();
await sync(); assert.equal(currentStatus, 'reading');
assert.equal(requests[0].ticks.reduce((s,t)=>s+t.activeMs,0),15000);
const beforeHidden=requests.length;
document.visibilityState='hidden';
for (let i=0; i<60; i++) tick();
await sync(); assert.equal(requests.length, beforeHidden, 'Background time excluded');
document.visibilityState='visible'; document.hasFocus=()=>false;
for (let i=0; i<5; i++) tick();
await sync(); assert.equal(requests.length,beforeHidden,'Unfocused window excluded');
document.hasFocus=()=>true;
for (let i=0; i<60; i++) tick();
assert.equal(currentStatus,'paused','Two idle minutes pauses the clock');
await sync();
const beforeIdle=requests.length;
for (let i=0; i<30; i++) tick();
await sync(); assert.equal(requests.length,beforeIdle,'No extra time while idle');
controls.resume(); for(let i=0;i<10;i++)tick(); await sync();
assert.equal(currentStatus,'reading'); assert.ok(requests.length>beforeIdle);
assert.ok(requests.every(r=>r.sessionId===requests[0].sessionId),'Resuming does not inflate session count');
cleanup();
console.log('Tracker checks passed: document readiness, visible/focused window, idle pause, resume and stable session identity.');
